function scaffoldArtDirection(entry) {
  const { id, name, identity, outfit, weapons, attack, spell, block, ko, south, portrait, banned, notes } = entry;
  const baseNegative = [
    'sword','axe','dagger','bow','crossbow','staff','wand','mace','spear','hammer','polearm',
    'gun','pistol','flail','scythe','whip','blade','longsword','greatsword','katana','rapier',
    'holding a','wielding','wields','visible pupil','visible iris',
  ];
  // Remove any banned entries that overlap with this character's actual weapon concept
  const uniqBanned = Array.from(new Set([...(banned || [])]));
  const refPrompt = [
    `IDENTITY (this image becomes the canonical identity anchor — preserve in every downstream frame): ${identity}`,
    `OUTFIT: ${outfit}`,
    `WEAPONS: ${weapons}`,
    `CLASS: humanoid. Full-body view, head to feet visible. Character occupies ~70% of the canvas height. Feet aligned near the bottom; headroom above.`,
    `POSE: full-body side profile facing right (east), calm combat-ready idle. Head up, eyes visible. NOT a portrait bust, NOT a close-up — entire character from head to feet.`,
    `STYLE: detailed pixel art with clean readable silhouette, warm pixel-art palette, transparent background, no ground shadow.`,
  ].join('\n\n');
  const poses = {
    portrait:    portrait,
    south:       south,
    east:        'Neutral combat idle, consistent with reference sheet, full-body facing east.',
    east_attack: attack,
    east_spell:  spell,
    east_block:  block,
    east_ko:     ko,
  };
  const framePrompt = (poseName, poseDesc) => [
    `IDENTITY (must match reference sheet exactly): ${identity}`,
    `OUTFIT: ${outfit}`,
    `WEAPONS: ${weapons}`,
    `POSE (${poseName}): ${poseDesc}`,
    `FRAMING: ${poseName === 'portrait' ? 'bust shot from mid-chest up, three-quarter view, centered in a 256x256 canvas, shoulders fill the lower third.' : 'full body, feet on bottom edge of 256x256 canvas.'}`,
    `SCALE (non-negotiable): character must occupy approximately 180px of the 256px canvas height — roughly 70%. Do NOT stretch or upscale. Extra space above head and/or below feet is correct.`,
    `STYLE: pixel art, transparent background, no ground shadow, no borders, no text. Match the palette and style of the reference sheet.`,
    `NEGATIVE: do not add weapons or props not listed in WEAPONS. Do not change palette, species, or outfit from the reference sheet. Do not zoom in — respect SCALE.`,
  ].join('\n\n');
  return {
    $schema: '../../schemas/v1/art-direction.json',
    spriteId: id,
    displayName: name,
    class: 'humanoid',
    pixelHeight: 180,
    identity,
    outfit,
    weapons,
    attackStyle: attack,
    spellStyle: spell,
    blockStyle: block,
    koStyle: ko,
    southStyle: south,
    portraitStyle: portrait,
    bannedSubstrings: uniqBanned,
    referenceSheet: {
      path: `images/pixellab/${id}/reference.png`,
      spritecookAssetId: null,
      prompt: refPrompt,
      bitforgeAssetId: null,
      sourcePortraitPath: `images/portraits/${id}.png`,
      generatedAt: null,
      approvedAt: null,
    },
    frames: Object.fromEntries(Object.entries(poses).map(([pose, desc]) => [pose, {
      path: `images/spritecook/${id}_${pose}.png`,
      prompt: framePrompt(pose, desc),
      generatedAt: null,
      approvedAt: null,
      spritecookAssetId: null,
    }])),
    notes,
  };
}

function main() {
  const args = process.argv.slice(2);
  const force = args.includes('--force');
  if (!fs.existsSync(AD_DIR)) fs.mkdirSync(AD_DIR, { recursive: true });
  const state = JSON.parse(fs.readFileSync(STATE, 'utf8'));

  const zeroFrames = () => ({
    portrait: 'pending', south: 'pending', east: 'pending',
    east_attack: 'pending', east_spell: 'pending', east_block: 'pending', east_ko: 'pending',
  });

  for (const c of CLASSES) {
    const adPath = path.join(AD_DIR, `${c.id}.json`);
    if (fs.existsSync(adPath) && !force) {
      console.log(`[skip] ${c.id}: already has art_direction JSON`);
    } else {
      const ad = scaffoldArtDirection(c);
      fs.writeFileSync(adPath, JSON.stringify(ad, null, 2) + '\n');
      console.log(`[write] ${c.id}: ${path.relative(REPO_ROOT, adPath)}`);
    }
    if (!state.characters[c.id]) {
      state.characters[c.id] = {
        spriteId: c.id,
        status: 'pending',
        referenceStatus: 'pending',
        framesStatus: zeroFrames(),
        artDirectionPath: `data/art_direction/${c.id}.json`,
        candidateDir: `images/pixellab/${c.id}`,
        originalSpritecookPrefix: `images/spritecook/${c.id}_`,
        creditsUsed: 0,
        notes: c.notes || '',
      };
      console.log(`[state] ${c.id}: registered`);
    }
  }
  state.updatedAt = new Date().toISOString();
  fs.writeFileSync(STATE, JSON.stringify(state, null, 2) + '\n');
  console.log(`\nDone. ${CLASSES.length} classes processed.`);
}

main();
